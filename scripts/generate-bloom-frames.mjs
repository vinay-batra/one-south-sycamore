/**
 * Frames for the hero particle figure.
 *
 * The figure is a point cloud built from Vince's own photographs: each
 * point takes its colour from a pixel, so it can never look like a
 * hand-modelled flower. Two outputs per photograph:
 *
 *   <slug>.webp         180x240, the grid the browser samples
 *   <slug>-poster.webp  1200x1600, the still shown until the cloud arrives
 *
 * Both come from the same crop, so the crossfade between them does not
 * jump. Reading a 2400px master in the browser to throw 99% of it away
 * would be silly, which is why the sampling size is baked here.
 *
 *   node scripts/generate-bloom-frames.mjs
 */
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import sharp from "sharp";

/**
 * Crops are hand-picked, not centred. The masters are shot handheld in the
 * shop and all three have ceiling, strip light or fan across the top; at
 * nine thousand points a white ceiling reads as a hole, so each frame is
 * cropped down to the part that is actually flowers. Masters are 1800x2400.
 */
const FRAMES = [
  { slug: "roses-green-trick", crop: { left: 292, top: 780, width: 1215, height: 1620 } },
  { slug: "roses-hellebore", crop: { left: 187, top: 500, width: 1425, height: 1900 } },
  { slug: "cooler-doors", crop: { left: 90, top: 180, width: 1620, height: 2160 } },
];

const OUT = "public/bloom";
const POSTER_W = 1200;
const POSTER_H = 1600;

mkdirSync(OUT, { recursive: true });

const rows = [];

for (const { slug, crop } of FRAMES) {
  const base = sharp(`public/photos/${slug}.webp`).extract(crop);

  const sample = `${OUT}/${slug}.webp`;
  await base.clone().resize(180, 240, { fit: "cover" }).webp({ quality: 84 }).toFile(sample);

  const poster = `${OUT}/${slug}-poster.webp`;
  await base
    .clone()
    .resize(POSTER_W, POSTER_H, { fit: "cover" })
    .webp({ quality: 80 })
    .toFile(poster);

  const blur = await base
    .clone()
    .resize(12, 16, { fit: "cover" })
    .webp({ quality: 40 })
    .toBuffer();

  rows.push(
    `  {\n` +
      `    slug: "${slug}",\n` +
      `    sample: "/bloom/${slug}.webp",\n` +
      `    poster: "/bloom/${slug}-poster.webp",\n` +
      `    width: ${POSTER_W},\n` +
      `    height: ${POSTER_H},\n` +
      `    blurDataURL: "data:image/webp;base64,${blur.toString("base64")}",\n` +
      `  },`,
  );

  const kb = (path) => `${(statSync(path).size / 1024).toFixed(1)} KB`;
  console.log(`${slug}  sample ${kb(sample)}  poster ${kb(poster)}`);
}

writeFileSync(
  "lib/bloom-sources.ts",
  `/**\n` +
    ` * Generated by scripts/generate-bloom-frames.mjs. Do not edit by hand.\n` +
    ` * Captions and order live in lib/bloom.ts.\n` +
    ` */\n` +
    `export const BLOOM_SOURCES = [\n${rows.join("\n")}\n] as const;\n`,
);
console.log("wrote lib/bloom-sources.ts");
