/**
 * The three photographs the hero figure cycles through.
 *
 * One output each: a 1200x1600 master that WebGL uploads as a texture and
 * that the plain <img> underneath uses as its source, so the two share a
 * single download. Crops are hand-picked, not centred, because the masters
 * are shot handheld in the shop and all three carry ceiling, fan or strip
 * light across the top; the figure is the first thing on the page and
 * should be solidly flowers. Masters are 1800x2400.
 *
 *   node scripts/generate-hero-frames.mjs
 */
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const FRAMES = [
  { slug: "roses-green-trick", crop: { left: 431, top: 1150, width: 938, height: 1250 } },
  { slug: "roses-hellebore", crop: { left: 360, top: 672, width: 1044, height: 1392 } },
  { slug: "cooler-doors", crop: { left: 90, top: 180, width: 1620, height: 2160 } },
];

const OUT = "public/hero";
const W = 1200;
const H = 1600;

mkdirSync(OUT, { recursive: true });

const rows = [];

for (const { slug, crop } of FRAMES) {
  const base = sharp(`public/photos/${slug}.webp`).extract(crop);
  const file = `${OUT}/${slug}.webp`;

  await base.clone().resize(W, H, { fit: "cover" }).webp({ quality: 82 }).toFile(file);

  const blur = await base
    .clone()
    .resize(12, 16, { fit: "cover" })
    .webp({ quality: 40 })
    .toBuffer();

  rows.push(
    `  {\n` +
      `    slug: "${slug}",\n` +
      `    src: "/hero/${slug}.webp",\n` +
      `    width: ${W},\n` +
      `    height: ${H},\n` +
      `    blurDataURL: "data:image/webp;base64,${blur.toString("base64")}",\n` +
      `  },`,
  );

  console.log(`${file}  ${(statSync(file).size / 1024).toFixed(1)} KB`);
}

writeFileSync(
  "lib/hero-sources.ts",
  `/**\n` +
    ` * Generated by scripts/generate-hero-frames.mjs. Do not edit by hand.\n` +
    ` * Captions and order live in lib/hero-frames.ts.\n` +
    ` */\n` +
    `export const HERO_SOURCES = [\n${rows.join("\n")}\n] as const;\n`,
);
console.log("wrote lib/hero-sources.ts");
